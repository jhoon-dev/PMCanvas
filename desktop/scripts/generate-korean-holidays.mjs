import KoreanLunarCalendar from 'korean-lunar-calendar';
import { readFileSync, writeFileSync } from 'node:fs';

// KASI Korean lunar conversion, not the Chinese lunar calendar. This generator is
// build-time only; the desktop app needs neither a service key nor network access.
const lunar = new KoreanLunarCalendar();
const iso = (y, m, d) => `${y}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
const shift = (date, n) =>
  new Date(Date.parse(date + 'T00:00:00Z') + n * 86400000).toISOString().slice(0, 10);
const weekday = (date) => new Date(date + 'T00:00:00Z').getUTCDay();
const special = {
  '2020-04-15': '국회의원 선거일',
  '2020-08-17': '임시공휴일',
  '2022-03-09': '대통령 선거일',
  '2022-06-01': '전국동시지방선거일',
  '2023-10-02': '임시공휴일',
  '2024-04-10': '국회의원 선거일',
  '2024-10-01': '임시공휴일',
  '2025-01-27': '임시공휴일',
  '2025-06-03': '대통령 선거일',
  '2026-06-03': '전국동시지방선거일',
  '2028-04-12': '국회의원 선거일',
};
const all = {};
for (let year = 2020; year <= 2050; year++) {
  const days = new Map(),
    groups = [];
  function add(dates, name, substitute = false, lunarGroup = false) {
    for (const date of dates) days.set(date, [...(days.get(date) || []), name]);
    groups.push({ dates, name, substitute, lunarGroup });
  }
  const fixed = (month, day, name, substitute = false) =>
    add([iso(year, month, day)], name, substitute);
  const lunarDate = (month, day) => {
    if (!lunar.setLunarDate(year, month, day, false)) throw Error('Lunar range exceeded');
    const date = lunar.getSolarCalendar();
    return iso(date.year, date.month, date.day);
  };
  fixed(1, 1, '신정');
  const seollal = lunarDate(1, 1),
    chuseok = lunarDate(8, 15);
  add(
    [-1, 0, 1].map((n) => shift(seollal, n)),
    '설날',
    true,
    true,
  );
  fixed(3, 1, '삼일절', year >= 2022);
  if (year >= 2026) fixed(5, 1, '노동절', true);
  fixed(5, 5, '어린이날', true);
  add([lunarDate(4, 8)], '부처님오신날', year >= 2023);
  fixed(6, 6, '현충일');
  if (year >= 2026) fixed(7, 17, '제헌절', true);
  fixed(8, 15, '광복절', year >= 2021);
  add(
    [-1, 0, 1].map((n) => shift(chuseok, n)),
    '추석',
    true,
    true,
  );
  fixed(10, 3, '개천절', year >= 2021);
  fixed(10, 9, '한글날', year >= 2021);
  fixed(12, 25, '성탄절', year >= 2023);
  for (const [date, name] of Object.entries(special))
    if (date.startsWith(String(year))) add([date], name);
  const substitutes = new Map();
  for (const group of groups) {
    if (!group.substitute) continue;
    const cause =
      group.dates.find(
        (date) => weekday(date) === 0 || (!group.lunarGroup && weekday(date) === 6),
      ) || group.dates.find((date) => ![0, 6].includes(weekday(date)) && days.get(date).length > 1);
    if (!cause) continue;
    // One overlapping calendar date creates one substitute, even when the
    // national holiday is in the middle of a three-day lunar holiday (2028).
    const previous = substitutes.get(cause);
    substitutes.set(cause, {
      end: [previous?.end || '', group.dates.at(-1)].sort().at(-1),
      names: [...(previous?.names || []), group.name],
    });
  }
  for (const [, { end, names }] of [...substitutes].sort(([a], [b]) => a.localeCompare(b))) {
    let date = shift(end, 1);
    while ([0, 6].includes(weekday(date)) || days.has(date)) date = shift(date, 1);
    days.set(date, [names.join('·') + ' 대체공휴일']);
  }
  for (const [date, names] of [...days].sort(([a], [b]) => a.localeCompare(b)))
    all[date] = names.join('·');
}
writeFileSync(
  new URL('../../shared/browser/korean-holidays-data.js', import.meta.url),
  '/* korean-lunar-calendar@0.4.0\n' +
    readFileSync(
      new URL('../node_modules/korean-lunar-calendar/LICENSE', import.meta.url),
      'utf8',
    ) +
    '*/\n' +
    '// Generated by desktop/scripts/generate-korean-holidays.mjs. See desktop/HOLIDAYS.md.\n' +
    'export const KOREAN_HOLIDAYS = Object.freeze(' +
    JSON.stringify(all, null, 2) +
    ');\n',
);
console.log(`Generated ${Object.keys(all).length} Korean public holiday dates (2020–2050).`);
